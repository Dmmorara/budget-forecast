"""
Demo households, for presentations: sign up, declare a budget, and build up
spending history month by month until the forecaster has enough to work with.

SIMULATION ONLY, AND SYNTHETIC
------------------------------
Nothing here is a real household. The "login" is a name and a PIN, so a
presenter can come back to the household they made; it is not authentication.
Every demo household's id starts with `demo-`, so it can never collide with a
sandbox id, and every response about one says `isSynthetic: true`.

Spending is either typed in by the presenter (one transaction at a time) or
generated by `simulate`, which draws a plausible month from the declared budget.
The generator is seeded by household and month, so the same household replays
the same months in a rehearsal and on the day.

IN MEMORY, ON PURPOSE
---------------------
The store lives for the process. Render's free plan sleeps and restarts with a
clean disk anyway, so persisting would only pretend otherwise; each demo
starts from nothing, and the sandbox extract is never written to.

THE MONTH IN PROGRESS
---------------------
A demo household lives through one month at a time. `month`/`year` is the
month in progress: the one forecast, and the one a typed-in spend lands in.
Simulating fills it in and moves on to the next. The first month in progress
is the month after the sandbox data ends, which is also after the model's
training period, so the fitted model is allowed to answer once three months
have been simulated.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
import threading
import zlib
from calendar import monthrange
from dataclasses import dataclass, field
from datetime import datetime

import numpy as np
import pandas as pd

from app.synthetic import RECORD_COLUMNS, monthly_totals

DEMO_PREFIX = "demo-"

# Limits that keep a public demo endpoint from growing without bound.
MAX_HOUSEHOLDS = 200
MAX_HISTORY_MONTHS = 36

# Paid once, early in the month, and close to the budget every time.
FIXED = {"Rent", "School Fees", "Savings"}

# How far a category's actual spend wanders from its budget, month to month.
FIXED_NOISE = 0.03
HABITUAL_NOISE = 0.15


class DemoError(Exception):
    """A request the store refuses. `status` is the HTTP status to answer with."""

    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status
        self.message = message


def is_demo(user_id: str) -> bool:
    return user_id.startswith(DEMO_PREFIX)


def _hash_pin(pin: str, salt: bytes) -> bytes:
    # A demo PIN, but still never kept in the clear.
    return hashlib.pbkdf2_hmac("sha256", pin.encode(), salt, 50_000)


def _seed(*parts: object) -> int:
    """A stable seed: Python's own hash() changes from one process to the next."""
    return zlib.crc32("|".join(map(str, parts)).encode())


@dataclass
class DemoHousehold:
    user_id: str
    name: str
    salt: bytes
    pin_hash: bytes
    year: int
    month: int
    budget: dict[str, float] = field(default_factory=dict)
    records: list[dict] = field(default_factory=list)
    history_months: int = 0

    def advance(self) -> None:
        self.year, self.month = (self.year + 1, 1) if self.month == 12 else (self.year, self.month + 1)

    def spent_this_month(self) -> dict[str, float]:
        out: dict[str, float] = {}
        for r in self.records:
            when = r["occurred_on"]
            if when.year == self.year and when.month == self.month:
                out[r["category"]] = round(out.get(r["category"], 0.0) + r["amount"], 2)
        return out


def _habit(user_id: str, category: str) -> float:
    """
    How this household tends to spend against a category's budget: a fixed
    factor per household and category, so one household runs a little over on
    groceries every month while another comes in under. Without it every
    household would spend its budget on average and the forecast would only
    ever echo the budget back.
    """
    if category in FIXED:
        return 1.0
    return float(np.random.default_rng(_seed(user_id, category)).uniform(0.85, 1.15))


def simulate_month(household: DemoHousehold, year: int, month: int) -> list[dict]:
    """One month of transactions drawn from the household's budget."""
    rng = np.random.default_rng(_seed(household.user_id, year, month))
    days = monthrange(year, month)[1]
    out = []
    for category, allocated in sorted(household.budget.items()):
        if allocated <= 0:
            continue
        fixed = category in FIXED
        noise = FIXED_NOISE if fixed else HABITUAL_NOISE
        total = allocated * _habit(household.user_id, category) * rng.lognormal(0.0, noise)
        if fixed:
            parts = [total]
            when = [int(rng.integers(1, 6))]
        else:
            n = int(rng.integers(3, 7))
            parts = list(total * rng.dirichlet(np.ones(n) * 2.0))
            when = list(rng.integers(1, days + 1, size=n))
        for amount, day in zip(parts, when):
            out.append({
                "user_id": household.user_id,
                "occurred_on": datetime(year, month, int(day), int(rng.integers(7, 21))),
                "category": category,
                "amount": round(float(amount), 2),
                "is_synthetic": True,
            })
    return out


class DemoStore:
    """Every demo household, in memory. Thread-safe: uvicorn may serve requests concurrently."""

    def __init__(self, first_month: tuple[int, int]):
        self.first_month = first_month
        self._lock = threading.Lock()
        self._households: dict[str, DemoHousehold] = {}
        self._by_name: dict[str, str] = {}
        # Rebuilt only after a write to that household.
        self._frames: dict[str, tuple[pd.DataFrame, pd.DataFrame]] = {}

    # ── sign up and log in ──

    def signup(self, name: str, pin: str) -> DemoHousehold:
        key = name.strip().casefold()
        with self._lock:
            if key in self._by_name:
                raise DemoError(409, "A demo household with that name already exists. Log in instead.")
            if len(self._households) >= MAX_HOUSEHOLDS:
                raise DemoError(503, "The demo is full. Restart the service to clear it.")
            user_id = DEMO_PREFIX + secrets.token_hex(3)
            while user_id in self._households:
                user_id = DEMO_PREFIX + secrets.token_hex(3)
            salt = secrets.token_bytes(16)
            household = DemoHousehold(
                user_id=user_id, name=name.strip(), salt=salt,
                pin_hash=_hash_pin(pin, salt),
                year=self.first_month[0], month=self.first_month[1],
            )
            self._households[user_id] = household
            self._by_name[key] = user_id
            return household

    def login(self, name: str, pin: str) -> DemoHousehold:
        with self._lock:
            user_id = self._by_name.get(name.strip().casefold())
            household = self._households.get(user_id) if user_id else None
        # The same answer for an unknown name and a wrong PIN.
        if household is None or not hmac.compare_digest(
            household.pin_hash, _hash_pin(pin, household.salt)
        ):
            raise DemoError(401, "No demo household matches that name and PIN.")
        return household

    def find(self, user_id: str) -> DemoHousehold | None:
        return self._households.get(user_id)

    def get(self, user_id: str) -> DemoHousehold:
        household = self.find(user_id)
        if household is None:
            raise DemoError(404, f"No demo household {user_id}. The service may have restarted.")
        return household

    # ── building history ──

    def set_budget(self, user_id: str, allocated: dict[str, float]) -> DemoHousehold:
        with self._lock:
            household = self.get(user_id)
            household.budget = {c.strip(): float(v) for c, v in allocated.items() if c.strip()}
            return household

    def add_spend(self, user_id: str, category: str, amount: float, day: int | None) -> DemoHousehold:
        with self._lock:
            household = self.get(user_id)
            last = monthrange(household.year, household.month)[1]
            day = min(day or 15, last)
            household.records.append({
                "user_id": user_id,
                "occurred_on": datetime(household.year, household.month, day, 12),
                "category": category.strip(),
                "amount": round(float(amount), 2),
                "is_synthetic": True,
            })
            self._frames.pop(user_id, None)
            return household

    def simulate(self, user_id: str, months: int) -> DemoHousehold:
        """Fill in the month in progress, keeping anything typed in, and move on. `months` times."""
        with self._lock:
            household = self.get(user_id)
            if not household.budget:
                raise DemoError(409, "Set a budget first: the simulated months are drawn from it.")
            months = min(months, MAX_HISTORY_MONTHS - household.history_months)
            if months <= 0:
                raise DemoError(409, f"A demo household holds at most {MAX_HISTORY_MONTHS} months.")
            for _ in range(months):
                household.records.extend(simulate_month(household, household.year, household.month))
                household.history_months += 1
                household.advance()
            self._frames.pop(user_id, None)
            return household

    # ── what the forecaster and insights read ──

    def _build(self, user_id: str) -> tuple[pd.DataFrame, pd.DataFrame]:
        with self._lock:
            cached = self._frames.get(user_id)
            if cached is not None:
                return cached
            household = self._households.get(user_id)
            rows = list(household.records) if household else []
            records = pd.DataFrame(rows, columns=RECORD_COLUMNS)
            records["amount"] = records["amount"].astype(float)
            monthly = monthly_totals(records) if rows else pd.DataFrame(
                columns=["user_id", "year", "month", "category", "amount"]
            )
            self._frames[user_id] = (records, monthly)
            return records, monthly

    def transactions(self, user_id: str) -> pd.DataFrame:
        return self._build(user_id)[0]

    def monthly(self, user_id: str) -> pd.DataFrame:
        return self._build(user_id)[1]
